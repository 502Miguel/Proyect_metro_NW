-- 1. Estado actual de las lineas
CREATE OR REPLACE VIEW VW_ESTADO_LINEAS AS
SELECT l.COD_LINEA,
       l.NOMBRE,
       l.COLOR_MAPA,
       l.TIPO_SERVICIO,
       l.ESTADO_OPERATIVO,
       eo.NOMBRE AS TERMINAL_ORIGEN,
       ed.NOMBRE AS TERMINAL_DESTINO,
       (SELECT COUNT(*) FROM LINEA_ESTACION le
         WHERE le.COD_LINEA = l.COD_LINEA) AS TOTAL_ESTACIONES,
       (SELECT COUNT(*) FROM LINEA_ESTACION le JOIN ESTACION e ON e.ID_ESTACION = le.ID_ESTACION
         WHERE le.COD_LINEA = l.COD_LINEA AND e.ESTADO_OPERATIVO <> 'OPERATIVA') AS ESTACIONES_CERRADAS,
       (SELECT COUNT(*) FROM RUTA r
         WHERE r.COD_LINEA = l.COD_LINEA AND r.ESTADO = 'ACTIVA') AS RUTAS_ACTIVAS,
       (SELECT COUNT(*) FROM RUTA r
         WHERE r.COD_LINEA = l.COD_LINEA AND r.ESTADO = 'AFECTADA_POR_CIERRE') AS RUTAS_AFECTADAS,
       (SELECT COUNT(*) FROM VIAJE_PROGRAMADO v JOIN RUTA r ON r.ID_RUTA = v.ID_RUTA
         WHERE r.COD_LINEA = l.COD_LINEA AND v.SALIDA_PROGRAMADA >= SYSDATE
           AND v.ESTADO_VIAJE IN ('PROGRAMADO', 'RETRASADO')) AS VIAJES_PENDIENTES
FROM LINEA l
JOIN ESTACION eo ON eo.ID_ESTACION = l.ID_TERMINAL_ORIGEN
JOIN ESTACION ed ON ed.ID_ESTACION = l.ID_TERMINAL_DESTINO;

-- 2. Proximas salidas por estacion: hora estimada en que cada viaje
--    pendiente sale de cada parada (salida del viaje + minutos de la parada)
CREATE OR REPLACE VIEW VW_PROXIMAS_SALIDAS AS
SELECT e.ID_ESTACION,
       e.NOMBRE AS ESTACION,
       r.COD_LINEA,
       r.CODIGO_RUTA,
       r.SENTIDO,
       des.NOMBRE AS DESTINO,
       v.ID_VIAJE,
       v.NUMERO_VIAJE,
       v.SALIDA_PROGRAMADA + d.MIN_SALIDA / 1440 AS HORA_SALIDA_ESTIMADA,
       v.ESTADO_VIAJE,
       t.CODIGO_INTERNO AS TREN
FROM VIAJE_PROGRAMADO v
JOIN RUTA r          ON r.ID_RUTA = v.ID_RUTA
JOIN DETALLE_RUTA d  ON d.ID_RUTA = v.ID_RUTA AND d.SE_DETIENE = 'S'
JOIN ESTACION e      ON e.ID_ESTACION = d.ID_ESTACION
JOIN ESTACION des    ON des.ID_ESTACION = r.ID_ESTACION_DESTINO
LEFT JOIN TREN t     ON t.ID_TREN = v.ID_TREN
WHERE v.ESTADO_VIAJE IN ('PROGRAMADO', 'EN_ABORDAJE', 'RETRASADO')
  AND d.ID_ESTACION <> r.ID_ESTACION_DESTINO
  AND e.ESTADO_OPERATIVO = 'OPERATIVA'
  AND v.SALIDA_PROGRAMADA + d.MIN_SALIDA / 1440 >= SYSDATE;

-- 3. Viajes retrasados: 5 minutos o mas de retraso en la salida o en la llegada
CREATE OR REPLACE VIEW VW_VIAJES_RETRASADOS AS
SELECT v.ID_VIAJE,
       v.NUMERO_VIAJE,
       r.COD_LINEA,
       r.CODIGO_RUTA,
       v.FECHA_VIAJE,
       v.SALIDA_PROGRAMADA,
       v.SALIDA_REAL,
       v.LLEGADA_PROGRAMADA,
       v.LLEGADA_REAL,
       ROUND((v.SALIDA_REAL - v.SALIDA_PROGRAMADA) * 1440)   AS MINUTOS_RETRASO_SALIDA,
       ROUND((v.LLEGADA_REAL - v.LLEGADA_PROGRAMADA) * 1440) AS MINUTOS_RETRASO_LLEGADA,
       v.ESTADO_VIAJE,
       t.CODIGO_INTERNO AS TREN,
       c.NOMBRES || ' ' || c.APELLIDOS AS CONDUCTOR
FROM VIAJE_PROGRAMADO v
JOIN RUTA r           ON r.ID_RUTA = v.ID_RUTA
LEFT JOIN TREN t      ON t.ID_TREN = v.ID_TREN
LEFT JOIN EMPLEADO c  ON c.ID_EMPLEADO = v.ID_CONDUCTOR
WHERE v.ESTADO_VIAJE = 'RETRASADO'
   OR (v.SALIDA_REAL - v.SALIDA_PROGRAMADA) * 1440 >= 5
   OR (v.LLEGADA_REAL - v.LLEGADA_PROGRAMADA) * 1440 >= 5;

-- 4. Trenes disponibles ahora (estado, inspeccion, mantenimientos y viajes en curso)
CREATE OR REPLACE VIEW VW_TRENES_DISPONIBLES AS
SELECT t.ID_TREN,
       t.CODIGO_INTERNO,
       m.NOMBRE_MODELO,
       m.FABRICANTE,
       m.DIVISION,
       t.CAPACIDAD_TOTAL,
       d.NOMBRE AS DEPOSITO,
       t.KILOMETRAJE_ACUMULADO,
       t.FECHA_PROXIMA_INSPECCION
FROM TREN t
JOIN MODELO_TREN m ON m.ID_MODELO = t.ID_MODELO
JOIN DEPOSITO d    ON d.ID_DEPOSITO = t.ID_DEPOSITO
WHERE t.ESTADO_OPERATIVO = 'DISPONIBLE'
  AND FN_TREN_DISPONIBLE(t.ID_TREN) = 'S';

-- 5. Trenes en mantenimiento o con una orden abierta
CREATE OR REPLACE VIEW VW_TRENES_MANTENIMIENTO AS
SELECT t.ID_TREN,
       t.CODIGO_INTERNO,
       t.ESTADO_OPERATIVO,
       o.NUMERO_ORDEN,
       o.TIPO_MANTENIMIENTO,
       o.PRIORIDAD,
       o.ESTADO AS ESTADO_ORDEN,
       o.FECHA_PROGRAMADA,
       o.FECHA_INICIO,
       tec.NOMBRES || ' ' || tec.APELLIDOS AS TECNICO_RESPONSABLE,
       t.FECHA_PROXIMA_INSPECCION,
       CASE WHEN t.FECHA_PROXIMA_INSPECCION < TRUNC(SYSDATE) THEN 'S' ELSE 'N' END AS INSPECCION_VENCIDA
FROM TREN t
LEFT JOIN EQUIPO e              ON e.ID_TREN = t.ID_TREN
LEFT JOIN ORDEN_MANTENIMIENTO o ON o.ID_EQUIPO = e.ID_EQUIPO
                               AND o.ESTADO IN ('SOLICITADA', 'PROGRAMADA', 'EN_EJECUCION', 'SUSPENDIDA')
LEFT JOIN EMPLEADO tec          ON tec.ID_EMPLEADO = o.ID_TECNICO_RESPONSABLE
WHERE t.ESTADO_OPERATIVO = 'EN_MANTENIMIENTO'
   OR o.ID_ORDEN IS NOT NULL;

-- 6. Incidentes abiertos, con cuanto tiempo llevan y que afectan
CREATE OR REPLACE VIEW VW_INCIDENTES_ABIERTOS AS
SELECT i.ID_INCIDENTE,
       i.NUMERO_INCIDENTE,
       i.TIPO_INCIDENTE,
       i.SEVERIDAD,
       i.ESTADO,
       i.LUGAR_AFECTADO,
       i.FECHA_HORA_INICIO,
       ROUND((SYSDATE - i.FECHA_HORA_INICIO) * 24, 1) AS HORAS_ABIERTO,
       rep.NOMBRES || ' ' || rep.APELLIDOS AS REPORTADO_POR,
       (SELECT COUNT(*) FROM INCIDENTE_ELEMENTO ie WHERE ie.ID_INCIDENTE = i.ID_INCIDENTE) AS ELEMENTOS_AFECTADOS,
       (SELECT COUNT(*) FROM INCIDENTE_VIAJE iv WHERE iv.ID_INCIDENTE = i.ID_INCIDENTE) AS VIAJES_AFECTADOS,
       i.PASAJEROS_AFECTADOS
FROM INCIDENTE i
JOIN EMPLEADO rep ON rep.ID_EMPLEADO = i.ID_REPORTADO_POR
WHERE i.ESTADO <> 'CERRADO';

-- 7. Ingresos diarios por linea.
--    El torniquete no sabe que linea toma el pasajero: en estaciones con
--    varias lineas, cada ingreso se reparte en partes iguales entre ellas
--    (asi la suma de todas las lineas cuadra con lo recaudado).
CREATE OR REPLACE VIEW VW_INGRESOS_DIARIOS_LINEA AS
SELECT TRUNC(vp.FECHA_HORA_INGRESO)            AS FECHA,
       le.COD_LINEA,
       l.NOMBRE                                AS LINEA,
       ROUND(SUM(1 / n.N_LINEAS), 1)           AS PASAJEROS,
       ROUND(SUM(vp.MONTO_COBRADO / n.N_LINEAS), 2) AS MONTO_RECAUDADO
FROM VIAJE_PASAJERO vp
JOIN LINEA_ESTACION le ON le.ID_ESTACION = vp.ID_ESTACION_INGRESO
JOIN LINEA l           ON l.COD_LINEA = le.COD_LINEA
JOIN (SELECT ID_ESTACION, COUNT(*) AS N_LINEAS FROM LINEA_ESTACION GROUP BY ID_ESTACION) n
                       ON n.ID_ESTACION = vp.ID_ESTACION_INGRESO
WHERE vp.ESTADO IN ('ABIERTO', 'CERRADO')
GROUP BY TRUNC(vp.FECHA_HORA_INGRESO), le.COD_LINEA, l.NOMBRE;

-- 8. Estaciones con mayor cantidad de pasajeros (ingresos + salidas)
CREATE OR REPLACE VIEW VW_ESTACIONES_MAS_PASAJEROS AS
SELECT e.ID_ESTACION,
       e.NOMBRE,
       e.BOROUGH,
       NVL(i.INGRESOS, 0)                      AS INGRESOS,
       NVL(s.SALIDAS, 0)                       AS SALIDAS,
       NVL(i.INGRESOS, 0) + NVL(s.SALIDAS, 0)  AS FLUJO_TOTAL,
       NVL(i.MONTO, 0)                         AS MONTO_RECAUDADO,
       RANK() OVER (ORDER BY NVL(i.INGRESOS, 0) + NVL(s.SALIDAS, 0) DESC) AS POSICION
FROM ESTACION e
LEFT JOIN (SELECT ID_ESTACION_INGRESO AS ID_EST, COUNT(*) AS INGRESOS, SUM(MONTO_COBRADO) AS MONTO
           FROM VIAJE_PASAJERO WHERE ESTADO IN ('ABIERTO', 'CERRADO')
           GROUP BY ID_ESTACION_INGRESO) i ON i.ID_EST = e.ID_ESTACION
LEFT JOIN (SELECT ID_ESTACION_SALIDA AS ID_EST, COUNT(*) AS SALIDAS
           FROM VIAJE_PASAJERO WHERE ID_ESTACION_SALIDA IS NOT NULL
           GROUP BY ID_ESTACION_SALIDA) s ON s.ID_EST = e.ID_ESTACION;

-- 9. Certificaciones vencidas o que vencen en los proximos 60 dias
CREATE OR REPLACE VIEW VW_CERTIFICACIONES_POR_VENCER AS
SELECT c.ID_CERTIFICACION,
       e.NUMERO_EMPLEADO,
       e.NOMBRES || ' ' || e.APELLIDOS AS EMPLEADO,
       ca.NOMBRE_CARGO AS CARGO,
       c.TIPO_CERTIFICACION,
       c.FECHA_VENCIMIENTO,
       TRUNC(c.FECHA_VENCIMIENTO) - TRUNC(SYSDATE) AS DIAS_RESTANTES,
       CASE WHEN c.FECHA_VENCIMIENTO < TRUNC(SYSDATE) THEN 'VENCIDA' ELSE 'POR VENCER' END AS SITUACION
FROM CERTIFICACION c
JOIN EMPLEADO e ON e.ID_EMPLEADO = c.ID_EMPLEADO
JOIN CARGO ca   ON ca.ID_CARGO = e.ID_CARGO
WHERE c.ESTADO IN ('VIGENTE', 'VENCIDA')
  AND c.FECHA_VENCIMIENTO < TRUNC(SYSDATE) + 60
  AND e.ESTADO_LABORAL = 'ACTIVO';
