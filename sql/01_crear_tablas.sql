    TIPO_CERTIFICACION      VARCHAR2(50)  NOT NULL,
    FECHA_EMISION           DATE          NOT NULL,
    FECHA_VENCIMIENTO       DATE          NOT NULL,
    INSTITUCION_EMISORA     VARCHAR2(100) NOT NULL,
