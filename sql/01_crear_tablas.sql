/* =====================================================================
   SISTEMA DE GESTION - METRO DE NUEVA YORK
   Script de creacion de tablas (Oracle 12c o superior: usa IDENTITY)

   Orden: Modulo 1 Red -> 2 Rutas/Horarios -> 3 Trenes -> 4 Personal
          -> 5 Pasajeros/Tarjetas -> 6 Mantenimiento -> 7 Incidentes -> Bitacora

   Convenciones:
   - Banderas S/N como CHAR(1) con CHECK.
   - Estados y tipos fijos se validan con CHECK (no tablas catalogo),
     para mantener el modelo cerca de las 30 entidades sugeridas.
   - Las fechas con hora usan DATE (Oracle guarda fecha + hora).
   - Las reglas que dependen de otras filas (traslapes, tren en
     mantenimiento, certificacion vigente, estacion cerrada) NO se pueden
     expresar con CHECK: van en triggers / procedimientos PL/SQL.
   ===================================================================== */

/* =====================================================================
   MODULO 1: RED E INFRAESTRUCTURA
   ===================================================================== */

CREATE TABLE ESTACION (
    ID_ESTACION             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO_ESTACION         VARCHAR2(10)  NOT NULL,
    NOMBRE                  VARCHAR2(100) NOT NULL,
    DIRECCION               VARCHAR2(200),
    BOROUGH                 VARCHAR2(20)  NOT NULL,
    LATITUD                 NUMBER(9,6)   NOT NULL,
    LONGITUD                NUMBER(9,6)   NOT NULL,
    FECHA_INAUGURACION      DATE,
    CANTIDAD_ACCESOS        NUMBER(3)     DEFAULT 1 NOT NULL,
    CANTIDAD_PLATAFORMAS    NUMBER(2)     DEFAULT 1 NOT NULL,
    TIPO_ESTACION           VARCHAR2(20)  NOT NULL,
    ESTADO_OPERATIVO        VARCHAR2(20)  DEFAULT 'OPERATIVA' NOT NULL,
    HORARIO_FUNCIONAMIENTO  VARCHAR2(50)  DEFAULT '24 HORAS',
    ACCESIBLE_DISCAPACIDAD  CHAR(1)       DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_ESTACION PRIMARY KEY (ID_ESTACION),
    CONSTRAINT UQ_ESTACION_CODIGO UNIQUE (CODIGO_ESTACION),
    CONSTRAINT CK_ESTACION_BOROUGH CHECK (BOROUGH IN ('MANHATTAN','BROOKLYN','QUEENS','THE BRONX','STATEN ISLAND')),
    CONSTRAINT CK_ESTACION_TIPO CHECK (TIPO_ESTACION IN ('LOCAL','EXPRESA','TERMINAL','TRANSFERENCIA')),
    CONSTRAINT CK_ESTACION_ESTADO CHECK (ESTADO_OPERATIVO IN ('OPERATIVA','CERRADA_TEMPORAL','CERRADA')),
    CONSTRAINT CK_ESTACION_ACCESIBLE CHECK (ACCESIBLE_DISCAPACIDAD IN ('S','N')),
    CONSTRAINT CK_ESTACION_LATITUD CHECK (LATITUD BETWEEN -90 AND 90),
    CONSTRAINT CK_ESTACION_LONGITUD CHECK (LONGITUD BETWEEN -180 AND 180),
    CONSTRAINT CK_ESTACION_ACCESOS CHECK (CANTIDAD_ACCESOS >= 1),
    CONSTRAINT CK_ESTACION_PLATAF CHECK (CANTIDAD_PLATAFORMAS >= 1)
);
-- Nota: "estacion temporalmente cerrada" se modela como ESTADO_OPERATIVO,
-- no como tipo, porque una estacion expresa tambien puede cerrarse.
-- Disponibilidad de elevadores/escaleras: se consulta en EQUIPO (modulo 6).

CREATE TABLE LINEA (
    COD_LINEA               VARCHAR2(10)  NOT NULL,
    NOMBRE                  VARCHAR2(50)  NOT NULL,
    COLOR_MAPA              VARCHAR2(20)  NOT NULL,
    ID_TERMINAL_ORIGEN      NUMBER        NOT NULL,
    ID_TERMINAL_DESTINO     NUMBER        NOT NULL,
    ESTADO_OPERATIVO        VARCHAR2(20)  DEFAULT 'ACTIVA' NOT NULL,
    TIPO_SERVICIO           VARCHAR2(20)  NOT NULL,
    FECHA_INAUGURACION      DATE,
    LONGITUD_KM             NUMBER(6,2),
    OPERADOR_RESPONSABLE    VARCHAR2(50)  DEFAULT 'MTA NEW YORK CITY TRANSIT',
    CONSTRAINT PK_LINEA PRIMARY KEY (COD_LINEA),
    CONSTRAINT UQ_LINEA_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT FK_LINEA_TERM_ORIGEN FOREIGN KEY (ID_TERMINAL_ORIGEN) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT FK_LINEA_TERM_DESTINO FOREIGN KEY (ID_TERMINAL_DESTINO) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT CK_LINEA_TERMINALES CHECK (ID_TERMINAL_ORIGEN <> ID_TERMINAL_DESTINO),
    -- INACTIVA = linea "desactivada" (no se borra)
    CONSTRAINT CK_LINEA_ESTADO CHECK (ESTADO_OPERATIVO IN ('ACTIVA','SUSPENDIDA','EN_MANTENIMIENTO','INACTIVA')),
    CONSTRAINT CK_LINEA_TIPO_SERV CHECK (TIPO_SERVICIO IN ('LOCAL','EXPRESO','NOCTURNO','ESPECIAL','TEMPORAL')),
    CONSTRAINT CK_LINEA_LONGITUD CHECK (LONGITUD_KM > 0)
);

CREATE TABLE PLATAFORMA (
