   MODULO 3: TRENES Y VAGONES
   ===================================================================== */

CREATE TABLE DEPOSITO (
    ID_DEPOSITO             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE                  VARCHAR2(60)  NOT NULL,
    DIRECCION               VARCHAR2(200),
    BOROUGH                 VARCHAR2(20)  NOT NULL,
    CAPACIDAD_TRENES        NUMBER(4),
    CONSTRAINT PK_DEPOSITO PRIMARY KEY (ID_DEPOSITO),
    CONSTRAINT UQ_DEPOSITO_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_DEPOSITO_BOROUGH CHECK (BOROUGH IN ('MANHATTAN','BROOKLYN','QUEENS','THE BRONX','STATEN ISLAND')),
    CONSTRAINT CK_DEPOSITO_CAPACIDAD CHECK (CAPACIDAD_TRENES > 0)
);

CREATE TABLE MODELO_TREN (
    ID_MODELO               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE_MODELO           VARCHAR2(30)  NOT NULL,
    FABRICANTE              VARCHAR2(50)  NOT NULL,
    DIVISION                CHAR(1)       NOT NULL,
    VELOCIDAD_MAXIMA_KMH    NUMBER(5,2),
    CONSTRAINT PK_MODELO_TREN PRIMARY KEY (ID_MODELO),
    CONSTRAINT UQ_MODELO_NOMBRE UNIQUE (NOMBRE_MODELO),
    -- A = lineas numeradas (IRT), B = lineas con letra (BMT/IND)
    CONSTRAINT CK_MODELO_DIVISION CHECK (DIVISION IN ('A','B')),
    CONSTRAINT CK_MODELO_VELOCIDAD CHECK (VELOCIDAD_MAXIMA_KMH > 0)
);

-- FABRICANTE no se repite aqui: depende del modelo (3FN).
CREATE TABLE TREN (
    ID_TREN                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO_INTERNO          VARCHAR2(20)  NOT NULL,
    ID_MODELO               NUMBER        NOT NULL,
    ANIO_FABRICACION        NUMBER(4)     NOT NULL,
    CAPACIDAD_TOTAL         NUMBER(5)     NOT NULL,
    ESTADO_OPERATIVO        VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    KILOMETRAJE_ACUMULADO   NUMBER(10,2)  DEFAULT 0 NOT NULL,
    ID_DEPOSITO             NUMBER        NOT NULL,
    FECHA_ULTIMA_INSPECCION DATE,
    FECHA_PROXIMA_INSPECCION DATE,
    CONSTRAINT PK_TREN PRIMARY KEY (ID_TREN),
    CONSTRAINT UQ_TREN_CODIGO UNIQUE (CODIGO_INTERNO),
    CONSTRAINT FK_TREN_MODELO FOREIGN KEY (ID_MODELO) REFERENCES MODELO_TREN (ID_MODELO),
    CONSTRAINT FK_TREN_DEPOSITO FOREIGN KEY (ID_DEPOSITO) REFERENCES DEPOSITO (ID_DEPOSITO),
    CONSTRAINT CK_TREN_ESTADO CHECK (ESTADO_OPERATIVO IN ('DISPONIBLE','EN_OPERACION','EN_MANTENIMIENTO','FUERA_DE_SERVICIO','RETIRADO')),
    CONSTRAINT CK_TREN_ANIO CHECK (ANIO_FABRICACION BETWEEN 1900 AND 2100),
    CONSTRAINT CK_TREN_CAPACIDAD CHECK (CAPACIDAD_TOTAL > 0),
    CONSTRAINT CK_TREN_KM CHECK (KILOMETRAJE_ACUMULADO >= 0),
    CONSTRAINT CK_TREN_INSPECCION CHECK (FECHA_PROXIMA_INSPECCION IS NULL OR FECHA_ULTIMA_INSPECCION IS NULL
                                         OR FECHA_PROXIMA_INSPECCION >= FECHA_ULTIMA_INSPECCION)
);

-- El vagon NO tiene ID_TREN: su tren actual se obtiene de COMPOSICION_TREN.
CREATE TABLE VAGON (
    ID_VAGON                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_SERIE            VARCHAR2(20)  NOT NULL,
    ID_MODELO               NUMBER        NOT NULL,
    TIPO_VAGON              VARCHAR2(20)  NOT NULL,
    CAPACIDAD_SENTADOS      NUMBER(3)     NOT NULL,
    CAPACIDAD_DE_PIE        NUMBER(3)     NOT NULL,
    ANIO_FABRICACION        NUMBER(4)     NOT NULL,
    ESTADO                  VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    ACCESIBLE               CHAR(1)       DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_VAGON PRIMARY KEY (ID_VAGON),
    CONSTRAINT UQ_VAGON_SERIE UNIQUE (NUMERO_SERIE),
    CONSTRAINT FK_VAGON_MODELO FOREIGN KEY (ID_MODELO) REFERENCES MODELO_TREN (ID_MODELO),
    CONSTRAINT CK_VAGON_TIPO CHECK (TIPO_VAGON IN ('MOTRIZ','REMOLQUE','CABINA')),
    CONSTRAINT CK_VAGON_ESTADO CHECK (ESTADO IN ('DISPONIBLE','EN_SERVICIO','EN_MANTENIMIENTO','FUERA_DE_SERVICIO','RETIRADO')),
    CONSTRAINT CK_VAGON_ACCESIBLE CHECK (ACCESIBLE IN ('S','N')),
    CONSTRAINT CK_VAGON_CAPACIDAD CHECK (CAPACIDAD_SENTADOS >= 0 AND CAPACIDAD_DE_PIE >= 0),
    CONSTRAINT CK_VAGON_ANIO CHECK (ANIO_FABRICACION BETWEEN 1900 AND 2100)
);

-- Historial de asignaciones vagon -> tren. FECHA_FIN NULL = asignacion actual.
CREATE TABLE COMPOSICION_TREN (
    ID_COMPOSICION          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_TREN                 NUMBER        NOT NULL,
    ID_VAGON                NUMBER        NOT NULL,
    POSICION                NUMBER(2)     NOT NULL,
    FECHA_INICIO            DATE          DEFAULT SYSDATE NOT NULL,
    FECHA_FIN               DATE,
    CONSTRAINT PK_COMPOSICION_TREN PRIMARY KEY (ID_COMPOSICION),
    CONSTRAINT FK_COMPOS_TREN FOREIGN KEY (ID_TREN) REFERENCES TREN (ID_TREN),
    CONSTRAINT FK_COMPOS_VAGON FOREIGN KEY (ID_VAGON) REFERENCES VAGON (ID_VAGON),
    CONSTRAINT CK_COMPOS_POSICION CHECK (POSICION >= 1),
    CONSTRAINT CK_COMPOS_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);
-- Regla 12: un vagon solo puede tener UNA asignacion abierta.
CREATE UNIQUE INDEX UX_COMPOS_VAGON_ACTIVO ON COMPOSICION_TREN (
    CASE WHEN FECHA_FIN IS NULL THEN ID_VAGON END
);
-- Dos vagones no pueden ocupar la misma posicion del mismo tren a la vez.
CREATE UNIQUE INDEX UX_COMPOS_POSICION_ACTIVA ON COMPOSICION_TREN (
    CASE WHEN FECHA_FIN IS NULL THEN ID_TREN END,
    CASE WHEN FECHA_FIN IS NULL THEN POSICION END
);

