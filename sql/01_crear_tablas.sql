    CONSTRAINT CK_EMPLEADO_FECHAS CHECK (FECHA_CONTRATACION > FECHA_NACIMIENTO),
    CONSTRAINT CK_EMPLEADO_CORREO CHECK (CORREO IS NULL OR CORREO LIKE '%_@_%._%')
);

CREATE TABLE CERTIFICACION (
    ID_CERTIFICACION        NUMBER GENERATED BY DEFAULT AS IDENTITY,
