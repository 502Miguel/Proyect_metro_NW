        'EMERGENCIA_MEDICA','ACCIDENTE','PROBLEMA_SEGURIDAD','OBJETO_EN_VIA','INUNDACION','INCENDIO',
        'CONGESTION','MANTENIMIENTO_NO_PROGRAMADO')),
    CONSTRAINT CK_INCIDENTE_SEVERIDAD CHECK (SEVERIDAD IN ('BAJO','MEDIO','ALTO','CRITICO')),
    CONSTRAINT CK_INCIDENTE_ESTADO CHECK (ESTADO IN ('ABIERTO','EN_ATENCION','CERRADO')),
    -- Regla 24
    CONSTRAINT CK_INCIDENTE_FECHAS CHECK (FECHA_HORA_FIN IS NULL OR FECHA_HORA_FIN >= FECHA_HORA_INICIO),
    CONSTRAINT CK_INCIDENTE_CERRADO CHECK (ESTADO <> 'CERRADO' OR FECHA_HORA_FIN IS NOT NULL),
    CONSTRAINT CK_INCIDENTE_PASAJEROS CHECK (PASAJEROS_AFECTADOS >= 0)
);

-- Regla 20: un incidente puede afectar varios elementos de la red.
-- TRAMO = segmento entre ID_ESTACION e ID_ESTACION_FIN de una linea.
CREATE TABLE INCIDENTE_ELEMENTO (
    ID_INCIDENTE_ELEMENTO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_INCIDENTE            NUMBER        NOT NULL,
    TIPO_ELEMENTO           VARCHAR2(20)  NOT NULL,
    ID_ESTACION             NUMBER,
    ID_ESTACION_FIN         NUMBER,
    COD_LINEA               VARCHAR2(10),
    ID_PLATAFORMA           NUMBER,
    ID_TREN                 NUMBER,
    ID_RUTA                 NUMBER,
    ID_EQUIPO               NUMBER,
    EFECTO                  VARCHAR2(30)  NOT NULL,
    CONSTRAINT PK_INCIDENTE_ELEMENTO PRIMARY KEY (ID_INCIDENTE_ELEMENTO),
    CONSTRAINT FK_INCELEM_INCIDENTE FOREIGN KEY (ID_INCIDENTE) REFERENCES INCIDENTE (ID_INCIDENTE),
    CONSTRAINT FK_INCELEM_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT FK_INCELEM_ESTACION_FIN FOREIGN KEY (ID_ESTACION_FIN) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT FK_INCELEM_LINEA FOREIGN KEY (COD_LINEA) REFERENCES LINEA (COD_LINEA),
    CONSTRAINT FK_INCELEM_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA) REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_INCELEM_TREN FOREIGN KEY (ID_TREN) REFERENCES TREN (ID_TREN),
    CONSTRAINT FK_INCELEM_RUTA FOREIGN KEY (ID_RUTA) REFERENCES RUTA (ID_RUTA),
    CONSTRAINT FK_INCELEM_EQUIPO FOREIGN KEY (ID_EQUIPO) REFERENCES EQUIPO (ID_EQUIPO),
    CONSTRAINT CK_INCELEM_TIPO CHECK (TIPO_ELEMENTO IN ('ESTACION','PLATAFORMA','TREN','RUTA','EQUIPO','TRAMO')),
    CONSTRAINT CK_INCELEM_ENLACE CHECK (
           (TIPO_ELEMENTO = 'ESTACION'   AND ID_ESTACION   IS NOT NULL)
        OR (TIPO_ELEMENTO = 'PLATAFORMA' AND ID_PLATAFORMA IS NOT NULL)
        OR (TIPO_ELEMENTO = 'TREN'       AND ID_TREN       IS NOT NULL)
        OR (TIPO_ELEMENTO = 'RUTA'       AND ID_RUTA       IS NOT NULL)
        OR (TIPO_ELEMENTO = 'EQUIPO'     AND ID_EQUIPO     IS NOT NULL)
        OR (TIPO_ELEMENTO = 'TRAMO'      AND COD_LINEA IS NOT NULL
                                         AND ID_ESTACION IS NOT NULL AND ID_ESTACION_FIN IS NOT NULL)),
    CONSTRAINT CK_INCELEM_EFECTO CHECK (EFECTO IN ('CIERRE_ESTACION','CIERRE_PLATAFORMA','SUSPENSION_TRAMO',
        'CAMBIO_RUTA','RETIRO_TREN','FALLA_EQUIPO','AFECTACION_PARCIAL'))
);

-- Viajes retrasados o cancelados por un incidente (M:N)
CREATE TABLE INCIDENTE_VIAJE (
    ID_INCIDENTE            NUMBER        NOT NULL,
    ID_VIAJE                NUMBER        NOT NULL,
    TIPO_AFECTACION         VARCHAR2(15)  NOT NULL,
    MINUTOS_RETRASO         NUMBER(5)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_INCIDENTE_VIAJE PRIMARY KEY (ID_INCIDENTE, ID_VIAJE),
