    DESCRIPCION             VARCHAR2(150),
    CONSTRAINT PK_CAT_SERVICIO PRIMARY KEY (ID_SERVICIO),
    CONSTRAINT UQ_CAT_SERVICIO_NOMBRE UNIQUE (NOMBRE_SERVICIO)
);

-- Entidad asociativa ESTACION <-> CAT_SERVICIO (M:N)
CREATE TABLE SERVICIO_ESTACION (
    ID_ESTACION             NUMBER        NOT NULL,
    ID_SERVICIO             NUMBER        NOT NULL,
    ESTADO                  VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT PK_SERVICIO_ESTACION PRIMARY KEY (ID_ESTACION, ID_SERVICIO),
    CONSTRAINT FK_SERVEST_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT FK_SERVEST_SERVICIO FOREIGN KEY (ID_SERVICIO) REFERENCES CAT_SERVICIO (ID_SERVICIO),
    CONSTRAINT CK_SERVEST_ESTADO CHECK (ESTADO IN ('DISPONIBLE','NO_DISPONIBLE'))
);

-- Entidad asociativa LINEA <-> ESTACION (M:N) con orden del recorrido
CREATE TABLE LINEA_ESTACION (
    ID_LINEA_ESTACION       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COD_LINEA               VARCHAR2(10)  NOT NULL,
    ID_ESTACION             NUMBER        NOT NULL,
    NUMERO_SECUENCIA        NUMBER(3)     NOT NULL,
    DISTANCIA_KM_ANTERIOR   NUMBER(5,2)   DEFAULT 0 NOT NULL,
    TIEMPO_MIN_ANTERIOR     NUMBER(4,1)   DEFAULT 0 NOT NULL,
    CONSTRAINT PK_LINEA_ESTACION PRIMARY KEY (ID_LINEA_ESTACION),
    CONSTRAINT UQ_LINEST_LINEA_EST UNIQUE (COD_LINEA, ID_ESTACION),
    CONSTRAINT UQ_LINEST_LINEA_SEC UNIQUE (COD_LINEA, NUMERO_SECUENCIA),
    CONSTRAINT FK_LINEST_LINEA FOREIGN KEY (COD_LINEA) REFERENCES LINEA (COD_LINEA),
    CONSTRAINT FK_LINEST_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT CK_LINEST_SECUENCIA CHECK (NUMERO_SECUENCIA >= 1),
    CONSTRAINT CK_LINEST_DISTANCIA CHECK (DISTANCIA_KM_ANTERIOR >= 0),
    CONSTRAINT CK_LINEST_TIEMPO CHECK (TIEMPO_MIN_ANTERIOR >= 0)
);

-- Transferencia entre dos lineas dentro de una estacion.
-- Las FK compuestas a LINEA_ESTACION obligan a que AMBAS lineas pasen
-- por la estacion -> cumple la regla 22 (al menos dos lineas).
CREATE TABLE TRANSFERENCIA (
    ID_TRANSFERENCIA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTACION             NUMBER        NOT NULL,
    COD_LINEA_ORIGEN        VARCHAR2(10)  NOT NULL,
    COD_LINEA_DESTINO       VARCHAR2(10)  NOT NULL,
    TIEMPO_CAMBIO_MIN       NUMBER(3)     NOT NULL,
    ACCESIBLE_DISCAPACIDAD  CHAR(1)       DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_TRANSFERENCIA PRIMARY KEY (ID_TRANSFERENCIA),
    CONSTRAINT UQ_TRANSF UNIQUE (ID_ESTACION, COD_LINEA_ORIGEN, COD_LINEA_DESTINO),
    CONSTRAINT FK_TRANSF_ORIGEN FOREIGN KEY (COD_LINEA_ORIGEN, ID_ESTACION) REFERENCES LINEA_ESTACION (COD_LINEA, ID_ESTACION),
    CONSTRAINT FK_TRANSF_DESTINO FOREIGN KEY (COD_LINEA_DESTINO, ID_ESTACION) REFERENCES LINEA_ESTACION (COD_LINEA, ID_ESTACION),
    CONSTRAINT CK_TRANSF_LINEAS CHECK (COD_LINEA_ORIGEN <> COD_LINEA_DESTINO),
    CONSTRAINT CK_TRANSF_TIEMPO CHECK (TIEMPO_CAMBIO_MIN > 0),
    CONSTRAINT CK_TRANSF_ACCESIBLE CHECK (ACCESIBLE_DISCAPACIDAD IN ('S','N'))
);

/* =====================================================================
   MODULO 2: RUTAS Y HORARIOS
   ===================================================================== */

CREATE TABLE RUTA (
    ID_RUTA                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO_RUTA             VARCHAR2(15)  NOT NULL,
    COD_LINEA               VARCHAR2(10)  NOT NULL,
    ID_ESTACION_ORIGEN      NUMBER        NOT NULL,
    ID_ESTACION_DESTINO     NUMBER        NOT NULL,
    SENTIDO                 VARCHAR2(20)  NOT NULL,
    TIPO_SERVICIO           VARCHAR2(20)  NOT NULL,
    DISTANCIA_TOTAL_KM      NUMBER(6,2),
    DURACION_ESTIMADA_MIN   NUMBER(5,1),
    ESTADO                  VARCHAR2(20)  DEFAULT 'ACTIVA' NOT NULL,
    FECHA_VIGENCIA_INICIO   DATE          NOT NULL,
    FECHA_VIGENCIA_FIN      DATE,
    CONSTRAINT PK_RUTA PRIMARY KEY (ID_RUTA),
    CONSTRAINT UQ_RUTA_CODIGO UNIQUE (CODIGO_RUTA),
    CONSTRAINT FK_RUTA_LINEA FOREIGN KEY (COD_LINEA) REFERENCES LINEA (COD_LINEA),
    CONSTRAINT FK_RUTA_EST_ORIGEN FOREIGN KEY (ID_ESTACION_ORIGEN) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT FK_RUTA_EST_DESTINO FOREIGN KEY (ID_ESTACION_DESTINO) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT CK_RUTA_EXTREMOS CHECK (ID_ESTACION_ORIGEN <> ID_ESTACION_DESTINO),
    CONSTRAINT CK_RUTA_SENTIDO CHECK (SENTIDO IN ('UPTOWN','DOWNTOWN','NORTE','SUR','ESTE','OESTE')),
    CONSTRAINT CK_RUTA_TIPO_SERV CHECK (TIPO_SERVICIO IN ('LOCAL','EXPRESO','NOCTURNO','ESPECIAL','TEMPORAL')),
    CONSTRAINT CK_RUTA_ESTADO CHECK (ESTADO IN ('ACTIVA','SUSPENDIDA','AFECTADA_POR_CIERRE','INACTIVA')),
    CONSTRAINT CK_RUTA_VIGENCIA CHECK (FECHA_VIGENCIA_FIN IS NULL OR FECHA_VIGENCIA_FIN >= FECHA_VIGENCIA_INICIO),
    CONSTRAINT CK_RUTA_DISTANCIA CHECK (DISTANCIA_TOTAL_KM > 0),
    CONSTRAINT CK_RUTA_DURACION CHECK (DURACION_ESTIMADA_MIN > 0)
);

-- Entidad DEBIL de RUTA: su PK incluye la PK de RUTA.
-- Las horas estimadas se guardan como minutos desde la salida del origen,
-- porque la ruta es una plantilla; la hora concreta de cada viaje es
-- VIAJE_PROGRAMADO.SALIDA_PROGRAMADA + MIN_LLEGADA / 1440.
CREATE TABLE DETALLE_RUTA (
    ID_RUTA                 NUMBER        NOT NULL,
    ORDEN_PARADA            NUMBER(3)     NOT NULL,
    ID_ESTACION             NUMBER        NOT NULL,
    MIN_LLEGADA             NUMBER(5,1)   NOT NULL,
    MIN_SALIDA              NUMBER(5,1)   NOT NULL,
    DISTANCIA_KM_ANTERIOR   NUMBER(5,2)   DEFAULT 0 NOT NULL,
    TIEMPO_MIN_ANTERIOR     NUMBER(4,1)   DEFAULT 0 NOT NULL,
    SE_DETIENE              CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_DETALLE_RUTA PRIMARY KEY (ID_RUTA, ORDEN_PARADA),
    CONSTRAINT UQ_DETRUTA_ESTACION UNIQUE (ID_RUTA, ID_ESTACION),
    CONSTRAINT FK_DETRUTA_RUTA FOREIGN KEY (ID_RUTA) REFERENCES RUTA (ID_RUTA),
    CONSTRAINT FK_DETRUTA_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION (ID_ESTACION),
    CONSTRAINT CK_DETRUTA_ORDEN CHECK (ORDEN_PARADA >= 1),
    CONSTRAINT CK_DETRUTA_TIEMPOS CHECK (MIN_LLEGADA >= 0 AND MIN_SALIDA >= MIN_LLEGADA),
    CONSTRAINT CK_DETRUTA_DISTANCIA CHECK (DISTANCIA_KM_ANTERIOR >= 0),
    CONSTRAINT CK_DETRUTA_TIEMPO_ANT CHECK (TIEMPO_MIN_ANTERIOR >= 0),
    -- 'N' = el tren pasa sin detenerse (servicio expreso)
    CONSTRAINT CK_DETRUTA_DETIENE CHECK (SE_DETIENE IN ('S','N'))
);

-- Horas de un horario: texto 'HH24:MI' (Oracle no tiene tipo TIME).
CREATE TABLE HORARIO (
    ID_HORARIO              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_RUTA                 NUMBER        NOT NULL,
    TIPO_DIA                VARCHAR2(20)  NOT NULL,
    DIA_SEMANA              VARCHAR2(10),
    FECHA_ESPECIAL          DATE,
    HORA_INICIO             VARCHAR2(5)   NOT NULL,
    HORA_FIN                VARCHAR2(5)   NOT NULL,
    FRECUENCIA_MIN          NUMBER(4,1)   NOT NULL,
    TIPO_SERVICIO           VARCHAR2(20)  NOT NULL,
    FECHA_VIGENCIA_DESDE    DATE          NOT NULL,
    FECHA_VIGENCIA_HASTA    DATE,
    CONSTRAINT PK_HORARIO PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_HORARIO_RUTA FOREIGN KEY (ID_RUTA) REFERENCES RUTA (ID_RUTA),
    CONSTRAINT CK_HORARIO_TIPO_DIA CHECK (TIPO_DIA IN ('LABORAL','FIN_SEMANA','FESTIVO','ESPECIAL')),
    CONSTRAINT CK_HORARIO_DIA_SEM CHECK (DIA_SEMANA IN ('LUNES','MARTES','MIERCOLES','JUEVES','VIERNES','SABADO','DOMINGO')),
    CONSTRAINT CK_HORARIO_ESPECIAL CHECK (TIPO_DIA <> 'ESPECIAL' OR FECHA_ESPECIAL IS NOT NULL),
    CONSTRAINT CK_HORARIO_HORA_INI CHECK (REGEXP_LIKE(HORA_INICIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_HORARIO_HORA_FIN CHECK (REGEXP_LIKE(HORA_FIN, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_HORARIO_FRECUENCIA CHECK (FRECUENCIA_MIN > 0),
    CONSTRAINT CK_HORARIO_TIPO_SERV CHECK (TIPO_SERVICIO IN ('LOCAL','EXPRESO','NOCTURNO','ESPECIAL','TEMPORAL')),
    CONSTRAINT CK_HORARIO_VIGENCIA CHECK (FECHA_VIGENCIA_HASTA IS NULL OR FECHA_VIGENCIA_HASTA >= FECHA_VIGENCIA_DESDE)
);
-- HORA_FIN puede ser menor que HORA_INICIO en servicio nocturno (cruza medianoche).

