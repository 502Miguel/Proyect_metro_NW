-- 1. ¿Que lineas pasan por una estacion determinada? (Ej. Fulton St)
SELECT E.NOMBRE AS ESTACION, L.COD_LINEA, L.NOMBRE AS LINEA, L.COLOR_HEX
FROM ESTACION E
JOIN LINEA_ESTACION LE ON E.ID_ESTACION = LE.ID_ESTACION
JOIN LINEA L ON LE.COD_LINEA = L.COD_LINEA
WHERE E.COD_ESTACION = 'FL-01'
ORDER BY L.COD_LINEA;

-- 2. ¿Cuales son las estaciones de una ruta y en que orden se visitan?
SELECT R.COD_RUTA, DR.ORDEN_PARADA, E.NOMBRE AS ESTACION, DR.PERMITE_PARADA_PASAJERO
FROM RUTA R
JOIN DETALLE_RUTA DR ON R.ID_RUTA = DR.ID_RUTA
JOIN ESTACION E ON DR.ID_ESTACION = E.ID_ESTACION
WHERE R.COD_RUTA = 'R-01-S'
ORDER BY DR.ORDEN_PARADA;

-- 3. ¿Que estaciones permiten transferencia entre lineas?
SELECT E.NOMBRE AS ESTACION_TRANSFERENCIA, T.COD_LINEA_ORIGEN, T.COD_LINEA_DESTINO, T.TIEMPO_ESTIMADO_MIN
FROM TRANSFERENCIA T
JOIN ESTACION E ON T.ID_ESTACION = E.ID_ESTACION;

-- 4. ¿Que viajes estan programados para una fecha especifica?
SELECT V.COD_VIAJE, R.COD_RUTA, V.HORA_PROGRAMADA_SALIDA, V.ESTADO_VIAJE
FROM VIAJE_PROGRAMADO V
JOIN RUTA R ON V.ID_RUTA = R.ID_RUTA
WHERE TRUNC(V.FECHA_VIAJE) = TO_DATE('2026-10-08', 'YYYY-MM-DD');

-- 5. ¿Que viajes presentan retrasos mayores a 15 minutos?
SELECT V.COD_VIAJE, V.HORA_PROGRAMADA_SALIDA, V.HORA_REAL_SALIDA,
       ROUND((CAST(V.HORA_REAL_SALIDA AS DATE) - CAST(V.HORA_PROGRAMADA_SALIDA AS DATE)) * 1440, 0) AS MINUTOS_RETRASO
FROM VIAJE_PROGRAMADO V
WHERE V.HORA_REAL_SALIDA IS NOT NULL 
  AND (CAST(V.HORA_REAL_SALIDA AS DATE) - CAST(V.HORA_PROGRAMADA_SALIDA AS DATE)) * 1440 > 15;

-- 6. ¿Que trenes estan disponibles para operacion?
SELECT T.COD_IDENTIFICADOR, M.NOMBRE_MODELO, T.CAPACIDAD_TOTAL, T.ESTADO_OPERATIVO
FROM TREN T
JOIN MODELO_TREN M ON T.ID_MODELO = M.ID_MODELO
WHERE T.ESTADO_OPERATIVO = 'Disponible';

-- 7. ¿Que trenes tienen inspeccion o mantenimiento vencido?
SELECT COD_IDENTIFICADOR, FECHA_PROX_INSPECCION, ESTADO_OPERATIVO
FROM TREN
WHERE FECHA_PROX_INSPECCION < SYSDATE;

-- 8. ¿Que conductor fue asignado a cada viaje?
SELECT V.COD_VIAJE, E.NUMERO_EMPLEADO, E.NOMBRE || ' ' || E.APELLIDO AS CONDUCTOR, AP.ROL_DESEMPENADO
FROM VIAJE_PROGRAMADO V
JOIN ASIGNACION_PERSONAL AP ON V.ID_VIAJE = AP.ID_VIAJE
JOIN EMPLEADO E ON AP.ID_EMPLEADO = E.ID_EMPLEADO
WHERE AP.ROL_DESEMPENADO LIKE '%Conductor%';

-- 9. ¿Cuanto dinero se recaudo por dia, estacion y tipo de tarifa?
SELECT TRUNC(VA.FECHA_HORA_INGRESO) AS FECHA, E.NOMBRE AS ESTACION, TT.NOMBRE_TARIFA, SUM(VA.MONTO_COBRADO) AS TOTAL_RECAUDADO
FROM VALIDACION_ACCESO VA
JOIN ESTACION E ON VA.ID_ESTACION_INGRESO = E.ID_ESTACION
JOIN CAT_TIPO_TARIFA TT ON VA.ID_TIPO_TARIFA_APLICADA = TT.ID_TIPO_TARIFA
GROUP BY TRUNC(VA.FECHA_HORA_INGRESO), E.NOMBRE, TT.NOMBRE_TARIFA
ORDER BY FECHA, TOTAL_RECAUDADO DESC;

-- 10. ¿Que incidentes permanecen abiertos?
SELECT NUM_INCIDENTE, TIPO_INCIDENTE, DESCRIPCION, NIVEL_SEVERIDAD, FECHA_HORA_INICIO
FROM INCIDENTE
WHERE ESTADO = 'Abierto'
ORDER BY FECHA_HORA_INICIO ASC;
