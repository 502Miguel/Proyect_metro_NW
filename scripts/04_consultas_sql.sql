PROMPT ===== 1. Que lineas pasan por una estacion determinada? (Ej. Times Sq-42 St) =====
SELECT E.NOMBRE AS ESTACION, L.COD_LINEA, L.NOMBRE AS LINEA, L.COLOR_MAPA, LE.NUMERO_SECUENCIA
FROM ESTACION E
JOIN LINEA_ESTACION LE ON LE.ID_ESTACION = E.ID_ESTACION
JOIN LINEA L           ON L.COD_LINEA = LE.COD_LINEA
WHERE E.NOMBRE = 'Times Sq-42 St'
ORDER BY L.COD_LINEA;

PROMPT ===== 2. Cuales son las estaciones de una ruta y en que orden se visitan? (Ej. ruta A-DT-EXP) =====
-- SE_DETIENE = 'N': el expreso pasa por la estacion sin detenerse
SELECT R.CODIGO_RUTA, DR.ORDEN_PARADA, E.NOMBRE AS ESTACION, DR.SE_DETIENE,
       DR.MIN_LLEGADA AS MINUTO_LLEGADA, DR.DISTANCIA_KM_ANTERIOR
FROM RUTA R
JOIN DETALLE_RUTA DR ON DR.ID_RUTA = R.ID_RUTA
JOIN ESTACION E      ON E.ID_ESTACION = DR.ID_ESTACION
WHERE R.CODIGO_RUTA = 'A-DT-EXP'
ORDER BY DR.ORDEN_PARADA;

PROMPT ===== 3. Que estaciones permiten transferencia entre lineas? =====
SELECT E.NOMBRE AS ESTACION, T.COD_LINEA_ORIGEN, T.COD_LINEA_DESTINO,
       T.TIEMPO_CAMBIO_MIN, T.ACCESIBLE_DISCAPACIDAD
FROM TRANSFERENCIA T
JOIN ESTACION E ON E.ID_ESTACION = T.ID_ESTACION
ORDER BY E.NOMBRE, T.COD_LINEA_ORIGEN, T.COD_LINEA_DESTINO;

PROMPT ===== 4. Que viajes estan programados para una fecha? (Ej. manana) =====
SELECT V.NUMERO_VIAJE, R.COD_LINEA, R.CODIGO_RUTA, V.SALIDA_PROGRAMADA, V.LLEGADA_PROGRAMADA,
       T.CODIGO_INTERNO AS TREN, V.ESTADO_VIAJE
FROM VIAJE_PROGRAMADO V
JOIN RUTA R      ON R.ID_RUTA = V.ID_RUTA
LEFT JOIN TREN T ON T.ID_TREN = V.ID_TREN
WHERE V.FECHA_VIAJE = TRUNC(SYSDATE) + 1
ORDER BY V.SALIDA_PROGRAMADA, R.CODIGO_RUTA;

PROMPT ===== 5. Que viajes presentan retrasos mayores a 15 minutos? =====
SELECT V.NUMERO_VIAJE, R.COD_LINEA, V.SALIDA_PROGRAMADA, V.SALIDA_REAL,
       ROUND((V.SALIDA_REAL - V.SALIDA_PROGRAMADA) * 1440) AS MINUTOS_RETRASO
FROM VIAJE_PROGRAMADO V
JOIN RUTA R ON R.ID_RUTA = V.ID_RUTA
WHERE V.SALIDA_REAL > V.SALIDA_PROGRAMADA + INTERVAL '15' MINUTE
ORDER BY MINUTOS_RETRASO DESC;

PROMPT ===== 6. Que trenes estan disponibles? =====
-- Disponible: estado DISPONIBLE, inspeccion al dia y sin mantenimiento pendiente que impida usarlo
SELECT T.CODIGO_INTERNO, M.NOMBRE_MODELO, M.DIVISION, T.CAPACIDAD_TOTAL,
       D.NOMBRE AS DEPOSITO, T.FECHA_PROXIMA_INSPECCION
FROM TREN T
JOIN MODELO_TREN M ON M.ID_MODELO = T.ID_MODELO
JOIN DEPOSITO D    ON D.ID_DEPOSITO = T.ID_DEPOSITO
WHERE T.ESTADO_OPERATIVO = 'DISPONIBLE'
  AND (T.FECHA_PROXIMA_INSPECCION IS NULL OR T.FECHA_PROXIMA_INSPECCION >= TRUNC(SYSDATE))
  AND NOT EXISTS (SELECT 1
                  FROM ORDEN_MANTENIMIENTO O JOIN EQUIPO EQ ON EQ.ID_EQUIPO = O.ID_EQUIPO
                  WHERE EQ.ID_TREN = T.ID_TREN
                    AND (O.ESTADO = 'EN_EJECUCION'
                         OR (O.ESTADO IN ('SOLICITADA', 'PROGRAMADA', 'SUSPENDIDA') AND O.PRIORIDAD IN ('ALTA', 'URGENTE'))))
ORDER BY T.CODIGO_INTERNO;

PROMPT ===== 7. Que trenes tienen mantenimiento vencido? =====
SELECT T.CODIGO_INTERNO, T.ESTADO_OPERATIVO, T.FECHA_ULTIMA_INSPECCION, T.FECHA_PROXIMA_INSPECCION,
       TRUNC(SYSDATE) - TRUNC(T.FECHA_PROXIMA_INSPECCION) AS DIAS_VENCIDO
FROM TREN T
WHERE T.FECHA_PROXIMA_INSPECCION < TRUNC(SYSDATE)
  AND T.ESTADO_OPERATIVO <> 'RETIRADO'
ORDER BY DIAS_VENCIDO DESC;

PROMPT ===== 8. Que conductor fue asignado a cada viaje? (Ej. viajes de ayer) =====
SELECT V.NUMERO_VIAJE, V.FECHA_VIAJE, R.CODIGO_RUTA, E.NUMERO_EMPLEADO,
       E.NOMBRES || ' ' || E.APELLIDOS AS CONDUCTOR, T.CODIGO_INTERNO AS TREN, V.ESTADO_VIAJE
FROM VIAJE_PROGRAMADO V
JOIN RUTA R      ON R.ID_RUTA = V.ID_RUTA
JOIN EMPLEADO E  ON E.ID_EMPLEADO = V.ID_CONDUCTOR
LEFT JOIN TREN T ON T.ID_TREN = V.ID_TREN
WHERE V.FECHA_VIAJE = TRUNC(SYSDATE) - 1
ORDER BY V.SALIDA_PROGRAMADA, R.CODIGO_RUTA;

PROMPT ===== 9. Cuantos pasajeros utilizaron cada linea durante un periodo? (Ej. ultimos 7 dias) =====
-- El torniquete registra la estacion, no la linea: en estaciones con varias
-- lineas cada ingreso se reparte en partes iguales entre ellas.
SELECT LE.COD_LINEA, L.NOMBRE AS LINEA, ROUND(SUM(1 / N.N_LINEAS), 1) AS PASAJEROS
FROM VIAJE_PASAJERO VP
JOIN LINEA_ESTACION LE ON LE.ID_ESTACION = VP.ID_ESTACION_INGRESO
JOIN LINEA L           ON L.COD_LINEA = LE.COD_LINEA
JOIN (SELECT ID_ESTACION, COUNT(*) AS N_LINEAS FROM LINEA_ESTACION GROUP BY ID_ESTACION) N
                       ON N.ID_ESTACION = VP.ID_ESTACION_INGRESO
WHERE VP.ESTADO IN ('ABIERTO', 'CERRADO')
  AND VP.FECHA_HORA_INGRESO >= TRUNC(SYSDATE) - 7
  AND VP.FECHA_HORA_INGRESO <  TRUNC(SYSDATE) + 1
GROUP BY LE.COD_LINEA, L.NOMBRE
ORDER BY PASAJEROS DESC;

PROMPT ===== 10. Cuanto dinero se recaudo por dia, estacion y tipo de tarifa? (Ej. ayer) =====
SELECT TRUNC(VP.FECHA_HORA_INGRESO) AS FECHA, E.NOMBRE AS ESTACION, TA.NOMBRE AS TARIFA,
       COUNT(*) AS VIAJES, SUM(VP.MONTO_COBRADO) AS RECAUDADO
FROM VIAJE_PASAJERO VP
JOIN ESTACION E ON E.ID_ESTACION = VP.ID_ESTACION_INGRESO
JOIN TARIFA TA  ON TA.ID_TARIFA = VP.ID_TARIFA
WHERE VP.ESTADO IN ('ABIERTO', 'CERRADO')
  AND VP.FECHA_HORA_INGRESO >= TRUNC(SYSDATE) - 1
  AND VP.FECHA_HORA_INGRESO <  TRUNC(SYSDATE)
GROUP BY TRUNC(VP.FECHA_HORA_INGRESO), E.NOMBRE, TA.NOMBRE
ORDER BY FECHA, ESTACION, TARIFA;

PROMPT ===== 11. Cuales son las estaciones con mayor flujo de pasajeros? =====
SELECT E.NOMBRE AS ESTACION, E.BOROUGH,
       SUM(F.INGRESO) AS INGRESOS, SUM(F.SALIDA) AS SALIDAS, SUM(F.INGRESO + F.SALIDA) AS FLUJO_TOTAL
FROM (SELECT ID_ESTACION_INGRESO AS ID_ESTACION, 1 AS INGRESO, 0 AS SALIDA
      FROM VIAJE_PASAJERO WHERE ESTADO IN ('ABIERTO', 'CERRADO')
      UNION ALL
      SELECT ID_ESTACION_SALIDA, 0, 1
      FROM VIAJE_PASAJERO WHERE ID_ESTACION_SALIDA IS NOT NULL) F
JOIN ESTACION E ON E.ID_ESTACION = F.ID_ESTACION
GROUP BY E.NOMBRE, E.BOROUGH
ORDER BY FLUJO_TOTAL DESC
FETCH FIRST 10 ROWS ONLY;

PROMPT ===== 12. Que incidentes permanecen abiertos? =====
SELECT I.NUMERO_INCIDENTE, I.TIPO_INCIDENTE, I.SEVERIDAD, I.ESTADO, I.LUGAR_AFECTADO,
       I.FECHA_HORA_INICIO, ROUND((SYSDATE - I.FECHA_HORA_INICIO) * 24, 1) AS HORAS_ABIERTO
FROM INCIDENTE I
WHERE I.ESTADO <> 'CERRADO'
ORDER BY I.FECHA_HORA_INICIO;

PROMPT ===== 13. Que linea acumulo mas retrasos? =====
-- Se cuenta como retraso salir 5 minutos o mas tarde (mismo umbral que VW_VIAJES_RETRASADOS)
SELECT R.COD_LINEA, L.NOMBRE AS LINEA,
       COUNT(*) AS VIAJES_RETRASADOS,
       SUM(ROUND((V.SALIDA_REAL - V.SALIDA_PROGRAMADA) * 1440)) AS MINUTOS_ACUMULADOS,
       RANK() OVER (ORDER BY SUM(ROUND((V.SALIDA_REAL - V.SALIDA_PROGRAMADA) * 1440)) DESC) AS POSICION
FROM VIAJE_PROGRAMADO V
JOIN RUTA R  ON R.ID_RUTA = V.ID_RUTA
JOIN LINEA L ON L.COD_LINEA = R.COD_LINEA
WHERE V.SALIDA_REAL >= V.SALIDA_PROGRAMADA + INTERVAL '5' MINUTE
GROUP BY R.COD_LINEA, L.NOMBRE
ORDER BY POSICION;

PROMPT ===== 14. Que tarjetas fueron bloqueadas o vencieron? =====
SELECT TJ.NUMERO_TARJETA,
       CASE WHEN P.ID_PASAJERO IS NULL THEN 'ANONIMA' ELSE P.NOMBRES || ' ' || P.APELLIDOS END AS PROPIETARIO,
       TJ.ESTADO, TJ.FECHA_VENCIMIENTO, TJ.SALDO,
       CASE WHEN TJ.ESTADO = 'BLOQUEADA' THEN 'BLOQUEADA' ELSE 'VENCIDA' END AS MOTIVO
FROM TARJETA TJ
LEFT JOIN PASAJERO P ON P.ID_PASAJERO = TJ.ID_PASAJERO
WHERE TJ.ESTADO IN ('BLOQUEADA', 'VENCIDA')
   OR TJ.FECHA_VENCIMIENTO < TRUNC(SYSDATE)
ORDER BY MOTIVO, TJ.NUMERO_TARJETA;

PROMPT ===== 15. Que tecnicos participaron en una orden de mantenimiento? (Ej. OM-2026-0001) =====
SELECT O.NUMERO_ORDEN, EQ.CODIGO_EQUIPO AS EQUIPO, O.TIPO_MANTENIMIENTO, E.NUMERO_EMPLEADO,
       E.NOMBRES || ' ' || E.APELLIDOS AS TECNICO, OT.HORAS_TRABAJADAS,
       CASE WHEN E.ID_EMPLEADO = O.ID_TECNICO_RESPONSABLE THEN 'RESPONSABLE' ELSE 'APOYO' END AS ROL
FROM ORDEN_MANTENIMIENTO O
JOIN EQUIPO EQ        ON EQ.ID_EQUIPO = O.ID_EQUIPO
JOIN ORDEN_TECNICO OT ON OT.ID_ORDEN = O.ID_ORDEN
JOIN EMPLEADO E       ON E.ID_EMPLEADO = OT.ID_EMPLEADO
WHERE O.NUMERO_ORDEN = 'OM-2026-0001'
ORDER BY ROL DESC, TECNICO;
